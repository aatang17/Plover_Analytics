"""Trace every number in draft.md to a value in data/ (all logged in log.md) -> verify.md.

A number matches if some source value, rendered the way the draft renders it, equals it:
$m values, %, pp, ×, $bn, share counts (m), prices, TSR points, dates and years.
Unmatched numbers are listed for manual resolution; nothing is auto-accepted.
"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, "data")
draft = open(os.path.join(HERE, "draft.md"), encoding="utf-8").read()

src = {}  # rendered string -> source description


def put(s, where):
    src.setdefault(s, where)


def fmt_all(v, where):
    """Register the renderings the draft uses for a value v (in $m unless noted)."""
    put("{:,.0f}".format(abs(v)), where)
    put("{:,.1f}".format(abs(v)), where)
    put("%.1f" % (abs(v) / 1000), where + " ($bn)")


for r in csv.DictReader(open(os.path.join(D, "derived.csv"))):
    v = float(r["value"])
    fmt_all(v, "derived.csv: " + r["key"])
    if r["unit"] in ("%", "pp", "x"):
        put("%.1f" % abs(v), "derived.csv: " + r["key"])
        put("%.0f" % abs(v), "derived.csv: " + r["key"])

for name in os.listdir(D):
    if not name.endswith(".csv") or name == "derived.csv":
        continue
    for r in csv.DictReader(l for l in open(os.path.join(D, name)) if not l.startswith("#")):
        for k in ("value", "ceo_total_pay", "ceo_actually_paid", "tsr", "peer_tsr"):
            if r.get(k) in (None, ""):
                continue
            try:
                v = float(r[k])
            except ValueError:
                continue
            where = "%s: %s %s" % (name, r.get("tag") or k, r.get("period_end") or r.get("fiscal_year") or "")
            if abs(v) >= 1e5:
                fmt_all(v / 1e6, where)
                put("{:,.0f}".format(abs(v) / 1e6), where)  # shares in m
            else:
                put("{:,.2f}".format(abs(v)), where)
                put("{:,.0f}".format(abs(v)), where)
                put("%.1f" % abs(v), where)

# Text facts from the 8-K, proxy footnotes and filing notes (log #52, #54, #55), and the as-of date.
TEXT = {"8": "8-K 2014-10-08 (log #52)", "2014": "8-K (log #52)", "24": "proxy footnote 4 (log #54)",
        "2020": "proxy footnote (log #54)", "29": "ATMP note (log #55)", "30": "WSA amendment date 2016-08-30 (log #53)",
        "85": "ATMP note (log #55)", "342": "ATMP note (log #55)", "14": "Xilinx acquisition date 2022-02-14 (log #53)",
        "31": "ZT Systems 2025-03-31 (log #53)", "500": "index name", "7.75": "debt instrument name (log #53)",
        "2.125": "debt instrument name (log #53)", "2026": "as-of year / note due year", "100": "$100 TSR base (log #51)",
        "25": "waiver instalment 25m (log #53)", "1.7": "Pensando 1.7bn (log #53)", "4.4": "ZT 4.4bn (log #53)",
        "48.8": "Xilinx 48.8bn (log #53)", "48.5": "Xilinx equity 48.5bn (log #53)", "2.0": "EESC range 2014–19 (derived)",
        "2.4": "EESC range 2014–19 (derived)"}
for k, v in TEXT.items():
    put(k, v)

body = draft.split("## Appendix")[0]
nums = re.findall(r"(?<![\w.])\d(?:[\d,]*\d)?(?:\.\d+)?", body)
rows, bad = [], []
for n in nums:
    if re.fullmatch(r"(19|20)\d\d", n) and n not in ("2014",):
        continue  # calendar years used as labels
    hit = src.get(n)
    rows.append((n, hit or "UNMATCHED"))
    if not hit:
        bad.append(n)

with open(os.path.join(HERE, "verify.md"), "w", encoding="utf-8") as f:
    f.write("# Verification — every number in draft.md\n\n"
            "Generated by verify.py: each number in the body (appendix excluded; calendar years excluded) is matched "
            "to a value in data/ rendered the same way. Every file in data/ is logged in log.md.\n\n"
            "| # | Number in draft | Source |\n|---|---|---|\n")
    for i, (n, w) in enumerate(rows, 1):
        f.write("| %d | %s | %s |\n" % (i, n, w))
    f.write("\n**check_claim:** not applicable — the Plover MCP `check_claim` tool checks Japanese cross-shareholding "
            "figures only (4-digit securities codes, yen); US figures are traced to the API series and filings instead.\n")
    f.write("\n**Reconciliation:** segment revenue sums to reported revenue in every year 2014–2025 (derived.csv, "
            "`seg sum check`, all 0.0).\n")
    f.write("\n**Result: %d numbers traced, %d unresolved.**\n" % (len(rows) - len(bad), len(bad)))
print("traced", len(rows) - len(bad), "unresolved", len(bad), sorted(set(bad)))
